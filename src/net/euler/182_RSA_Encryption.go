package main

import "fmt"

/*
Project Euler 182: RSA encryption (RSA 加密与未隐藏消息)

【题目目标】
已知 RSA 加密算法参数：p = 1009, q = 3643, n = p*q = 3675787
欧拉函数 phi(n) = (p-1)*(q-1) = 1008 * 3642 = 3671136
要求：寻找所有满足 1 < e < phi(n) 且 gcd(e, phi(n)) = 1 的公钥 e 中，
使得“未隐藏消息”（即 m^e ≡ m (mod n)）数量达到最小的所有 e 的总和。

【核心数学原理】
根据中国剩余定理 (CRT) 和模算术中的原根性质，对于任意合法的 RSA 公钥 e，
满足 m^e ≡ m (mod n) 的不动点（即加密后等于自身的明文）的总数量 N(e) 为：
N(e) = [1 + gcd(e-1, p-1)] * [1 + gcd(e-1, q-1)]

【极值推导】
为了让 N(e) 最小，我们需要让两个 gcd 的值尽可能小：
1. 因为 p, q 是奇质数，所以 p-1 (1008) 和 q-1 (3642) 必然是偶数。
2. 密钥 e 必须与 phi(n) 互质，所以 e 必然是奇数，因此 e-1 也必然是偶数。
3. 既然 e-1、p-1、q-1 都是偶数，那么这两个 gcd 的值至少为 2。
结论：N(e) 的理论最小值必然是：(1 + 2) * (1 + 2) = 9 个不动点。

【等价转换】
将原题的文字描述完全等价转化为纯粹的数论条件。
在 1 < e < 3671136 范围内，寻找所有满足以下 3 个条件的 e：
1. gcd(e, 3671136) == 1 (保证 e 作为公钥的合法性)
2. gcd(e-1, 1008) == 2  (保证模 p 域下不动点最少)
3. gcd(e-1, 3642) == 2  (保证模 q 域下不动点最少)

【极致剪枝策略 (时间复杂度降维)】
仔细观察条件 2：gcd(e-1, 1008) == 2
由于 1008 是 4 的倍数 (1008 = 4 * 252)，如果 e-1 也能被 4 整除，
那么它们的最大公约数至少会是 4，这就违背了等于 2 的条件。
这意味着：e-1 必须能被 2 整除，但绝对不能被 4 整除！
数学表达为：e-1 ≡ 2 (mod 4)
推导得出：  e ≡ 3 (mod 4)

算法应用：
我们根本不需要逐一遍历所有的奇数。外层循环可以直接从 e = 3 开始，
每次步长跳跃 4（即 3, 7, 11, 15...）。
这不仅天然避开了所有的偶数，还直接砍掉了 75% 的无效搜索空间，
让暴力枚举达到了近乎 O(1) 的执行手感。
*/

func main() {
	p, q := 1009, 3643
	ø := (p - 1) * (q - 1)
	sum := int64(0)
	for e := 3; e < ø; e += 4 {
		if gcd(e, ø) != 1 {
			continue
		}
		if gcd(e-1, p-1) == 2 && gcd(e-1, q-1) == 2 {
			sum += int64(e)
		}
	}
	fmt.Printf("sum=%d\n", sum)
}

func gcd(a, b int) int {
	for b != 0 {
		a, b = b, a%b
	}
	return a
}
